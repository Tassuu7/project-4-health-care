def lookup_icd10(code: str) -> Optional[Dict[str, str]]:
    """Search ICD-10 codification dictionary."""
    return ICD10_CATALOGUE.get(code.strip().upper())

def search_icd10_by_keyword(keyword: str, limit: int = 15) -> List[Dict[str, str]]:
    """Search diagnosis catalogue by text query."""
    kw = keyword.strip().lower()
    results = []
    for code, data in ICD10_CATALOGUE.items():
        if kw in code.lower() or kw in data["description"].lower() or kw in data["specialty"].lower():
            results.append(data)
            if len(results) >= limit:
                break
    return results
